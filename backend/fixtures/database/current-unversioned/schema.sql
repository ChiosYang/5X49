CREATE TABLE movie (
    id VARCHAR NOT NULL PRIMARY KEY,
    title VARCHAR NOT NULL,
    title_cn VARCHAR,
    year INTEGER NOT NULL,
    poster_local VARCHAR,
    backdrop_local VARCHAR,
    poster_thumb_local VARCHAR,
    backdrop_thumb_local VARCHAR,
    poster_path VARCHAR,
    backdrop_path VARCHAR,
    tmdb_id VARCHAR,
    imdb_id VARCHAR,
    overview VARCHAR,
    plot VARCHAR,
    director VARCHAR,
    runtime INTEGER,
    countries JSON,
    audio_tracks JSON,
    imdb_rating FLOAT,
    external_scores JSON,
    external_scores_updated_at VARCHAR,
    external_scores_error VARCHAR,
    genres JSON,
    actors JSON,
    analysis_status VARCHAR NOT NULL DEFAULT 'pending',
    micro_genre VARCHAR,
    micro_genre_definition VARCHAR,
    analysis_data JSON,
    folder_name VARCHAR,
    video_file VARCHAR,
    nfo_source VARCHAR,
    nfo_file VARCHAR,
    nfo_path VARCHAR,
    nfo_size INTEGER,
    nfo_mtime FLOAT,
    nfo_fingerprint VARCHAR,
    media_path VARCHAR,
    folder_path VARCHAR,
    file_size INTEGER,
    file_mtime FLOAT,
    video_width INTEGER,
    video_height INTEGER,
    video_codec VARCHAR,
    video_bitrate INTEGER,
    video_duration FLOAT,
    video_fps FLOAT,
    video_dynamic_range VARCHAR,
    video_bit_depth INTEGER,
    added_at VARCHAR,
    last_seen_at VARCHAR,
    missing_since VARCHAR,
    library_status VARCHAR NOT NULL DEFAULT 'available',
    metadata_updated_at VARCHAR,
    metadata_source VARCHAR,
    scrape_status VARCHAR NOT NULL DEFAULT 'pending',
    scrape_error VARCHAR,
    scraped_at VARCHAR,
    tmdb_confidence FLOAT
);

CREATE TABLE movie_user_state (
    movie_id VARCHAR NOT NULL PRIMARY KEY,
    watched BOOLEAN NOT NULL DEFAULT 0,
    watched_at VARCHAR,
    rating INTEGER,
    favorite BOOLEAN NOT NULL DEFAULT 0,
    notes VARCHAR,
    updated_at VARCHAR NOT NULL,
    FOREIGN KEY(movie_id) REFERENCES movie(id)
);

CREATE TABLE job (
    id VARCHAR NOT NULL PRIMARY KEY,
    type VARCHAR NOT NULL,
    status VARCHAR NOT NULL DEFAULT 'queued',
    payload JSON,
    progress JSON,
    result JSON,
    result_summary VARCHAR,
    error VARCHAR,
    attempts INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 1,
    priority INTEGER NOT NULL DEFAULT 0,
    dedupe_key VARCHAR,
    cancel_requested BOOLEAN NOT NULL DEFAULT 0,
    created_at VARCHAR NOT NULL,
    updated_at VARCHAR NOT NULL,
    started_at VARCHAR,
    finished_at VARCHAR
);

CREATE TABLE events (
    id VARCHAR NOT NULL PRIMARY KEY,
    aggregate_type VARCHAR NOT NULL,
    aggregate_id VARCHAR,
    type VARCHAR NOT NULL,
    actor_type VARCHAR NOT NULL DEFAULT 'system',
    actor_id VARCHAR,
    command_id VARCHAR,
    correlation_id VARCHAR,
    causation_id VARCHAR,
    payload JSON,
    context JSON,
    schema_version INTEGER NOT NULL DEFAULT 1,
    occurred_at VARCHAR NOT NULL
);

